#!/usr/bin/env python3
"""Localization tool (L1.1, docs/LOCALIZATION.md).

The source of every player-visible string is localization/strings.csv (one row per key: context hint, English, then per
translation the text, its review status and the hash of the English it was written for). The game reads only the
generated modules src/ReplicatedStorage/Strings/<lang>.luau; never edit those by hand.

    python tools/loc.py build    regenerate the Luau tables (+ the pseudo-language); marks translations whose English
                                 changed as "new"; rewrites the CSV in its canonical form
    python tools/loc.py check    missing / extra plural forms, placeholders and rich-text tags differing from English,
                                 stale generated files, keys the code uses that do not exist, keys nobody uses
    python tools/loc.py lint     player-visible text written as a literal in src/ (compared with a per-file baseline)
    python tools/loc.py review   translations waiting for review (status "new")

CSV conventions (the file opens in Excel by double-click):
  * UTF-8 with BOM, comma separated, CRLF; a "sep=," first line is accepted on input (EXCEL_SEP_LINE), and so is a
    semicolon file (Excel saves CSV with the system list separator)
  * a key starting with "#" is a section heading (ignored by the game)
  * plural keys: one row per form, key[one] / key[few] / key[other] (English uses one + other, Czech one + few + other)
  * escapes inside a cell: \\n = line break, \\\\ = backslash; a leading backslash is dropped, so "\\=" or "\\+" keeps
    Excel from reading the cell as a formula
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "localization" / "strings.csv"
SRC = ROOT / "src"
OUT_DIR = SRC / "ReplicatedStorage" / "Strings"
LINT_BASELINE = ROOT / "tools" / "loc_lint_baseline.txt"

SOURCE = "en"
TRANSLATIONS = ["cs"]  # a new language: add it here, to Locale.Supported / Order, and two CSV columns appear on build
PSEUDO = "qps"  # generated from English for testing (Studio and admins only)
PLURAL_FORMS = {"en": ["one", "other"], "cs": ["one", "few", "other"], PSEUDO: ["one", "other"]}
STATUSES = ("new", "ok")
# Excel ignores the UTF-8 BOM when the file starts with "sep=," and shows Czech letters garbled (checked 2026-10-24 with
# Microsoft 365, en-US); without the line Excel reads UTF-8 correctly and splits on the system list separator.
EXCEL_SEP_LINE = False

KEY_RE = re.compile(r"^[a-z][A-Za-z0-9]*(\.[A-Za-z0-9_]+)+$")
ROW_KEY_RE = re.compile(r"^(?P<base>[^\[\]]+)(\[(?P<form>one|few|other)\])?$")
PLACEHOLDER_RE = re.compile(r"\{(\w+)\}")
TAG_RE = re.compile(r"</?([a-zA-Z]+)[^>]*>")
GENERATED_HEADER = "-- GENERATED by tools/loc.py from localization/strings.csv ({lang}). Do not edit: edit the CSV and run\n-- `python tools/loc.py build`.\n"

# lint: files that stay English on purpose (admin and debug tools) and the Luau that is not game text
LINT_IGNORE = (
    "StarterGui/ScreenGui/AdminPanel/",
    "ServerScriptService/AdminCoinsServer",
    "ReplicatedStorage/Strings/",
    "ReplicatedStorage/Locale.luau",
    "/TopTimeScript.",  # legacy time-played board, Disabled
)
LINT_PATTERNS = [
    # label.Text = "…" / .ActionText / .ObjectText / .PlaceholderText, also string.format("…") and concatenations
    re.compile(r"\.(Text|ActionText|ObjectText|PlaceholderText)\s*=\s*(?P<rhs>.+)$"),
    # property tables: { Text = "…" }
    re.compile(r"(?<![\w.])(Text|ActionText|ObjectText|PlaceholderText)\s*=\s*(?P<rhs>.+)$"),
]
LITERAL_RE = re.compile(r'"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.)*)\'')
WORDY_RE = re.compile(r"[A-Za-z]{2,}")
# any other string that reads like prose (words with spaces, or a capitalised word with punctuation: "Sure?", "Loading...")
PROSE_RE = re.compile(r"[A-Za-z]{2,}[^\"']*\s[^\"']*[A-Za-z]{2,}|^[A-Z][a-z]+[.!?…]+$")
# lines whose literals are not shown to players: logs, instance / service / attribute names, requires
NOT_TEXT_RE = re.compile(r"\b(warn|print|error|assert|debugPrint)\s*\(|:(WaitForChild|FindFirstChild\w*|GetService|SetAttribute|GetAttribute\w*|GetPropertyChangedSignal|AddTag|HasTag|GetTagged|IsA)\s*\(|Instance\.new\s*\(|\brequire\s*\(|\.Name\s*[=~]=|\bName\s*=|ContentText|rbxasset")


# ---------------------------------------------------------------------------------------------------------------- CSV

def columns() -> list[str]:
    cols = ["key", "context", SOURCE]
    for lang in TRANSLATIONS:
        cols += [lang, f"{lang}_status", f"{lang}_en_hash"]
    return cols


def read_csv() -> list[dict]:
    raw = CSV_PATH.read_bytes().decode("utf-8-sig")
    lines = raw.splitlines(keepends=True)
    delimiter = None
    if lines and lines[0].lower().startswith("sep="):
        delimiter = lines[0].strip()[4:5] or ","
        raw = "".join(lines[1:])
    if delimiter is None:
        header = raw.split("\n", 1)[0]
        delimiter = ";" if header.count(";") > header.count(",") else ","
    reader = csv.DictReader(io.StringIO(raw, newline=""), delimiter=delimiter)
    rows = []
    for row in reader:
        clean = {col: (row.get(col) or "") for col in columns()}
        if not clean["key"].strip() and not any(clean[c] for c in columns()[1:]):
            continue  # empty line
        clean["key"] = clean["key"].strip()
        rows.append(clean)
    return rows


def same_text(path: Path, text: str) -> bool:
    """True when the file holds `text`, ignoring line endings (git may check files out with CRLF) and a UTF-8 BOM."""
    if not path.exists():
        return False
    current = path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")
    return current == text.lstrip("\ufeff").replace("\r\n", "\n")


def write_csv(rows: list[dict]) -> str:
    out = io.StringIO(newline="")
    if EXCEL_SEP_LINE:
        out.write("sep=,\r\n")
    writer = csv.DictWriter(out, fieldnames=columns(), lineterminator="\r\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({col: row.get(col, "") for col in columns()})
    return out.getvalue()


def unescape(cell: str) -> str:
    text = cell
    if text.startswith("\\") and len(text) > 1 and text[1] not in "n\\":
        text = text[1:]  # "\=" / "\+" … keeps Excel from treating the cell as a formula
    result, i = [], 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text) and text[i + 1] in "n\\":
            result.append("\n" if text[i + 1] == "n" else "\\")
            i += 2
            continue
        result.append(c)
        i += 1
    return "".join(result)


def is_section(row: dict) -> bool:
    return row["key"].startswith("#")


# ---------------------------------------------------------------------------------------------------------- strings

class Entry:
    """One key with its texts per language: a string, or {form: string} for plural keys."""

    def __init__(self, base: str):
        self.base = base
        self.plural = False
        self.rows: list[dict] = []
        self.forms: dict[str, dict[str, str]] = {}  # lang -> form ("" for singular) -> text


def collect(rows: list[dict], errors: list[str]) -> dict[str, Entry]:
    entries: dict[str, Entry] = {}
    seen = set()
    for row in rows:
        if is_section(row):
            continue
        key = row["key"]
        match = ROW_KEY_RE.match(key)
        if not match or not KEY_RE.match(match.group("base")):
            errors.append(f"{key}: malformed key (area.thing.detail, plural forms as key[one|few|other])")
            continue
        if key in seen:
            errors.append(f"{key}: duplicate row")
            continue
        seen.add(key)
        base, form = match.group("base"), match.group("form") or ""
        entry = entries.setdefault(base, Entry(base))
        if entry.rows and (form != "") != entry.plural:
            errors.append(f"{base}: mixes plural and singular rows")
        entry.plural = form != ""
        entry.rows.append(row)
        for lang in [SOURCE] + TRANSLATIONS:
            if row[lang] != "":
                entry.forms.setdefault(lang, {})[form] = unescape(row[lang])
    return entries


def english_hash(entry: Entry) -> str:
    texts = entry.forms.get(SOURCE, {})
    joined = "\x1f".join(f"{form}={texts[form]}" for form in sorted(texts))
    # "h" + 8 hex digits: always text in Excel (a bare "12e45678" would become a number and lose the review)
    return "h" + hashlib.sha1(joined.encode("utf-8")).hexdigest()[:8]


PSEUDO_MAP = str.maketrans(
    "aAcCdDeEiInNoOrRsStTuUyYzZ",
    "áÁčČďĎěĚíÍňŇöÖřŘšŠťŤůŮýÝžŽ",
)


def pseudo(text: str) -> str:
    """English made visibly 'translated': Czech-style accents (tests the glyphs), about 40 % longer (tests the space),
    brackets (text without them on screen is a literal in the code). Placeholders and rich-text tags stay intact."""
    parts = re.split(r"(\{\w+\}|<[^>]*>|\n)", text)
    letters = 0
    for i, part in enumerate(parts):
        if i % 2 == 0:
            letters += len(part)
            parts[i] = part.translate(PSEUDO_MAP)
    pad = "~" * max(2, round(letters * 0.4))
    return f"[!! {''.join(parts)} {pad} !!]"


def lang_table(entries: dict[str, Entry], lang: str) -> dict[str, object]:
    table: dict[str, object] = {}
    source_lang = SOURCE if lang == PSEUDO else lang
    for base, entry in entries.items():
        texts = entry.forms.get(source_lang)
        if not texts:
            continue
        if entry.plural:
            wanted = PLURAL_FORMS[lang]
            if lang == PSEUDO:
                forms = [pseudo(texts.get(form, "")) for form in wanted]
            else:
                forms = [texts.get(form) for form in wanted]
            if any(form is None for form in forms):
                continue  # incomplete: the game falls back to English, check reports it
            table[base] = forms
        else:
            text = texts.get("")
            if text is None:
                continue
            table[base] = pseudo(text) if lang == PSEUDO else text
    return table


def luau_string(text: str) -> str:
    out = ['"']
    for c in text:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "\r":
            out.append("\\r")
        elif c == "\t":
            out.append("\\t")
        elif ord(c) < 32:
            out.append(f"\\{ord(c):03d}")
        else:
            out.append(c)
    out.append('"')
    return "".join(out)


def render_luau(lang: str, table: dict[str, object], order: list[str]) -> str:
    lines = [GENERATED_HEADER.format(lang=lang), "return {\n"]
    for base in order:
        if base not in table:
            continue
        value = table[base]
        if isinstance(value, list):
            rendered = "{ " + ", ".join(luau_string(v) for v in value) + " }"
        else:
            rendered = luau_string(value)
        lines.append(f"\t[{luau_string(base)}] = {rendered},\n")
    lines.append("}\n")
    return "".join(lines)


def generated_files(entries: dict[str, Entry]) -> dict[Path, str]:
    order = list(entries.keys())
    files = {}
    for lang in [SOURCE] + TRANSLATIONS + [PSEUDO]:
        files[OUT_DIR / f"{lang}.luau"] = render_luau(lang, lang_table(entries, lang), order)
    return files


# ------------------------------------------------------------------------------------------------------------ build

def update_statuses(rows: list[dict], entries: dict[str, Entry]) -> list[str]:
    notes = []
    for entry in entries.values():
        current = english_hash(entry)
        for lang in TRANSLATIONS:
            has_text = lang in entry.forms
            for row in entry.rows:
                status_col, hash_col = f"{lang}_status", f"{lang}_en_hash"
                if not has_text:
                    row[status_col], row[hash_col] = "", ""
                    continue
                if row[status_col] not in STATUSES:
                    row[status_col] = "new"
                if row[hash_col] == "":
                    row[hash_col] = current
                elif row[hash_col] != current:
                    if row[status_col] != "new":
                        notes.append(f"{row['key']}: English changed, {lang} back to new")
                    row[status_col], row[hash_col] = "new", current
    return notes


def cmd_build(_args) -> int:
    rows = read_csv()
    errors: list[str] = []
    entries = collect(rows, errors)
    if errors:
        print("\n".join(errors))
        return 1
    for note in update_statuses(rows, entries):
        print(note)
    canonical = write_csv(rows)
    if not same_text(CSV_PATH, canonical) or not CSV_PATH.read_bytes().startswith(b"\xef\xbb\xbf"):
        CSV_PATH.write_bytes(("\ufeff" + canonical).encode("utf-8"))
        print(f"wrote {CSV_PATH.relative_to(ROOT)}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in generated_files(entries).items():
        if not same_text(path, text):
            path.write_bytes(text.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT)}")
    print(f"{len(entries)} keys")
    return 0


# ------------------------------------------------------------------------------------------------------------ check

def code_files() -> list[Path]:
    return [p for p in SRC.rglob("*.luau") if OUT_DIR not in p.parents]


def literals(text: str) -> list[str]:
    """String literals of Luau source, line by line with comments removed (an apostrophe in a comment is no literal)."""
    found = []
    in_block = False
    for line in text.splitlines():
        if in_block:
            if "]]" not in line:
                continue
            line = line.split("]]", 1)[1]
            in_block = False
        code = strip_comment(line)
        if code != line and line[len(code):].startswith("--[[") and "]]" not in line[len(code):]:
            in_block = True
        found += [m.group(1) if m.group(1) is not None else m.group(2) for m in LITERAL_RE.finditer(code)]
    return found


def tags(text: str) -> list[str]:
    return sorted(m.group(0) if m.group(0).startswith("</") else "<" + m.group(1) for m in TAG_RE.finditer(text))


def cmd_check(_args) -> int:
    rows = read_csv()
    errors: list[str] = []
    warnings: list[str] = []
    entries = collect(rows, errors)

    for base, entry in entries.items():
        en = entry.forms.get(SOURCE, {})
        wanted_en = PLURAL_FORMS[SOURCE] if entry.plural else [""]
        if set(en) != set(wanted_en):
            errors.append(f"{base}: English needs {', '.join(f or 'the text' for f in wanted_en)}")
            continue
        for lang in TRANSLATIONS:
            texts = entry.forms.get(lang, {})
            wanted = PLURAL_FORMS[lang] if entry.plural else [""]
            if not texts:
                errors.append(f"{base}: no {lang} text")
                continue
            if set(texts) != set(wanted):
                errors.append(f"{base}: {lang} needs the forms {', '.join(wanted)}")
                continue
            for form, text in texts.items():
                reference = en.get(form) or en.get("other") or en.get("")
                label = f"{base}[{form}]" if form else base
                if set(PLACEHOLDER_RE.findall(text)) != set(PLACEHOLDER_RE.findall(reference)):
                    errors.append(f"{label}: {lang} placeholders {sorted(set(PLACEHOLDER_RE.findall(text)))} differ from English {sorted(set(PLACEHOLDER_RE.findall(reference)))}")
                if tags(text) != tags(reference):
                    errors.append(f"{label}: {lang} rich-text tags differ from English")
            if any(row[f"{lang}_status"] == "new" for row in entry.rows):
                warnings.append(f"{base}: {lang} waiting for review")

    for row in rows:
        for col in [SOURCE] + TRANSLATIONS:
            cell = row[col]
            if cell[:1] in ("=", "@") or (cell[:1] in "+-" and cell[1:2].isalnum()):
                errors.append(f"{row['key']}: {col} starts with '{cell[:1]}' (Excel reads it as a formula): write \\{cell[:1]}")

    expected = generated_files(entries)
    for path, text in expected.items():
        if not same_text(path, text):
            errors.append(f"{path.relative_to(ROOT)} is out of date: run python tools/loc.py build")
    for path in OUT_DIR.glob("*.luau"):
        if path not in expected:
            errors.append(f"{path.relative_to(ROOT)}: not generated by loc.py (old string table?)")

    areas = {base.split(".")[0] for base in entries}
    used_literals = set()
    for path in code_files():
        text = path.read_text(encoding="utf-8")
        for lit in literals(text):
            used_literals.add(lit)
            if KEY_RE.match(lit) and lit.split(".")[0] in areas and lit not in entries:
                errors.append(f"{path.relative_to(ROOT)}: unknown key \"{lit}\"")
    prefixes = {lit for lit in used_literals if lit.endswith(".") and lit.split(".")[0] in areas}
    for base in entries:
        if base not in used_literals and not any(base.startswith(p) for p in prefixes):
            warnings.append(f"{base}: not used by any code")

    for line in errors:
        print("ERROR  " + line)
    for line in warnings:
        print("note   " + line)
    print(f"{len(entries)} keys, {len(errors)} errors, {len(warnings)} notes")
    return 1 if errors else 0


# ------------------------------------------------------------------------------------------------------------- lint

def strip_comment(line: str) -> str:
    """The line without a trailing -- comment (a "--" inside a string literal is kept)."""
    quote = None
    i = 0
    while i < len(line):
        c = line[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = None
        elif c in "\"'":
            quote = c
        elif line.startswith("--", i):
            return line[:i]
        i += 1
    return line


def lint_hits() -> dict[str, list[str]]:
    hits: dict[str, list[str]] = {}
    for path in code_files():
        rel = path.relative_to(SRC).as_posix()
        if any(part in rel for part in LINT_IGNORE):
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if "loc: ignore" in line:
                continue
            code = strip_comment(line)
            hit = False
            for pattern in LINT_PATTERNS:
                match = pattern.search(code)
                if not match:
                    continue
                rhs = match.group("rhs")
                if "Locale." in rhs:
                    continue
                if any(WORDY_RE.search(visible(lit)) and not KEY_RE.match(lit) for lit in literals(rhs)):
                    hit = True
                    break
            if not hit and not NOT_TEXT_RE.search(code) and "Locale." not in code:
                hit = any(PROSE_RE.search(visible(lit)) and not KEY_RE.match(lit) for lit in literals(code))
            if hit:
                hits.setdefault(rel, []).append(f"{rel}:{number}: {line.strip()[:110]}")
    return hits


def visible(literal: str) -> str:
    """What a player would read: without rich-text tags and format specifiers (<font color="%s">%s</font> is no text)."""
    return re.sub(r"<[^>]*>|%[-+ 0-9.]*[a-zA-Z]", " ", literal).strip()


def read_baseline() -> dict[str, int]:
    if not LINT_BASELINE.exists():
        return {}
    baseline = {}
    for line in LINT_BASELINE.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            count, rel = line.split(" ", 1)
            baseline[rel] = int(count)
    return baseline


def cmd_lint(args) -> int:
    hits = lint_hits()
    if args.update_baseline:
        lines = ["# loc.py lint baseline: literal texts per file still waiting for L2 / L3. Only ever lower these numbers.\n"]
        for rel in sorted(hits):
            lines.append(f"{len(hits[rel])} {rel}\n")
        LINT_BASELINE.write_text("".join(lines), encoding="utf-8", newline="\n")
        print(f"baseline: {sum(len(h) for h in hits.values())} literals in {len(hits)} files")
        return 0
    baseline = read_baseline()
    failed = False
    for rel in sorted(hits):
        allowed = baseline.get(rel, 0)
        if len(hits[rel]) > allowed:
            failed = True
            print(f"ERROR  {rel}: {len(hits[rel])} literal texts (baseline {allowed})")
            for hit in hits[rel]:
                print("       " + hit)
        elif args.verbose:
            for hit in hits[rel]:
                print("       " + hit)
    for rel, allowed in sorted(baseline.items()):
        count = len(hits.get(rel, []))
        if count < allowed:
            print(f"note   {rel}: {count} literal texts, baseline {allowed}: lower it with --update-baseline")
    total = sum(len(h) for h in hits.values())
    print(f"{total} literal texts in {len(hits)} files (baseline {sum(baseline.values())})")
    return 1 if failed else 0


# ----------------------------------------------------------------------------------------------------------- review

def cmd_review(args) -> int:
    rows = read_csv()
    langs = [args.lang] if args.lang else TRANSLATIONS
    count = 0
    for lang in langs:
        for row in rows:
            if not is_section(row) and row.get(f"{lang}_status") == "new":
                count += 1
                print(f"{row['key']}\n    context: {row['context']}\n    en: {row[SOURCE]}\n    {lang}: {row[lang]}\n")
    print(f"{count} waiting for review")
    return 0


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build").set_defaults(func=cmd_build)
    sub.add_parser("check").set_defaults(func=cmd_check)
    lint = sub.add_parser("lint")
    lint.add_argument("--update-baseline", action="store_true")
    lint.add_argument("--verbose", action="store_true")
    lint.set_defaults(func=cmd_lint)
    review = sub.add_parser("review")
    review.add_argument("--lang")
    review.set_defaults(func=cmd_review)
    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
